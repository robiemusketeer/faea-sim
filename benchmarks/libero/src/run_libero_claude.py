#!/usr/bin/env python3
"""
Systematically execute Claude Agent SDK on LIBERO benchmark tasks.

Usage:
    # List available benchmarks
    python run_libero_claude.py --list-benchmarks

    # List tasks in a benchmark
    python run_libero_claude.py --list-tasks --benchmark libero_10

    # Run a specific task (requires --experiment)
    python run_libero_claude.py --experiment exp_001 --task-id 0

    # Run all tasks (requires --experiment)
    python run_libero_claude.py --experiment exp_001 --all

Requirements:
    pip install claude-agent-sdk
"""

