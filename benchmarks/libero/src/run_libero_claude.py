# Configuration
SCRIPT_DIR = Path(__file__).parent.resolve()
SIM_EVAL_DIR = SCRIPT_DIR.parent
DATA_DIR = SIM_EVAL_DIR / "data"
BENCHMARKS_CONFIG = SCRIPT_DIR / "benchmarks.json"
PROMPT_TEMPLATE_PATH = SCRIPT_DIR / "prompt_template_baseline.md"
EXAMPLE_FILE = (SIM_EVAL_DIR.parent / "examples" / "libero_pick_place_policy.py").resolve()
HARNESS_FILE = (SCRIPT_DIR / "libero_harness.py").resolve()

# Default working directory for claude agent
AGENT_CWD = str(SIM_EVAL_DIR)


def list_benchmarks() -> dict:
    """List available benchmarks from config."""
    with open(BENCHMARKS_CONFIG) as f:
        return json.load(f)


def get_libero_tasks(benchmark_name: str = "libero_spatial") -> List[Tuple[int, str]]:
    """Get tasks directly from libero benchmark."""
    from libero.libero import benchmark

    bm_dict = benchmark.get_benchmark_dict()
    if benchmark_name not in bm_dict:
        available = list(bm_dict.keys())
        raise ValueError(f"Unknown benchmark '{benchmark_name}'. Available: {available}")

    bm = bm_dict[benchmark_name]()
    return [(i, name) for i, name in enumerate(bm.get_task_names())]


def load_prompt_template(custom_path: str | None = None) -> str:
    """Load the prompt template from the specified or default path."""
    template_path = Path(custom_path) if custom_path else PROMPT_TEMPLATE_PATH
    if not template_path.exists():
        raise FileNotFoundError(f"Prompt template not found: {template_path}")
    return template_path.read_text()


def generate_episode_scaffold(
    benchmark_name: str,
    task_id: int,
    output_dir: str,
    harness_path: str,
    meta_file: str,
    video_file: str,
    policy_file: str,
) -> str:
    """Return a self-contained scaffold script that imports and runs a policy.

    The scaffold handles sys.path setup, dynamic import of the policy file
    written by Claude, and invocation of run_episode from the harness.
    Claude never edits this file — it only writes the companion policy file.
    """
    harness_dir = str(Path(harness_path).parent.resolve())
    return f'''\
import sys
import importlib.util

sys.path.insert(0, {harness_dir!r})
from libero_harness import run_episode

spec = importlib.util.spec_from_file_location("policy_mod", {policy_file!r})
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)

run_episode(
    benchmark_name={benchmark_name!r},
    task_id={task_id!r},
    policy_fn=mod.policy,
    output_dir={output_dir!r},
    meta_file={meta_file!r},
    video_file={video_file!r},
)
'''


def format_prompt(template: str, task_id: int, task_description: str, output_dir: Path, benchmark_name: str, temp_dir: str) -> str:
    """
    Format the prompt template with task_id, task_description, and output directory.

    Uses {{PLACEHOLDER}} syntax for clear template markers.
    temp_dir must be pre-generated by the caller so it can be used for
    scaffold/policy file placement before the prompt is sent.
    """
    readable_task = task_description.replace("_", " ")

    scaffold_file = os.path.join(temp_dir, "scaffold.py")
    policy_file = os.path.join(temp_dir, f"policy_{task_id}.py")

    replacements = {
        "{{TASK_DESCRIPTION}}": readable_task,
        "{{TASK_ID}}": str(task_id),
        "{{BENCHMARK_NAME}}": benchmark_name,
        "{{META_FILE}}": f"meta_{task_id}.json",
        "{{EPISODE_FILE}}": f"episode_{task_id}.py",
        "{{VIDEO_FILE}}": f"episode_{task_id}.mp4",
        "{{OUTPUT_FOLDER}}": str(output_dir.resolve()),
        "{{TEMP_DIR}}": temp_dir,
        "{{EXAMPLE_FILE}}": str(EXAMPLE_FILE),
        "{{HARNESS_PATH}}": str(HARNESS_FILE),
        "{{SCAFFOLD_FILE}}": scaffold_file,
        "{{POLICY_FILE}}": policy_file,
    }

    formatted = template
    for placeholder, value in replacements.items():
        formatted = formatted.replace(placeholder, value)

    return formatted


def serialize_message(msg: Any) -> dict:
    """Serialize a message to a JSON-compatible dict."""
    try:
        if hasattr(msg, '__dataclass_fields__'):
            return asdict(msg)
        elif hasattr(msg, '__dict__'):
            return {k: serialize_message(v) for k, v in msg.__dict__.items()}
        else:
            return str(msg)
    except Exception:
        return str(msg)


def validate_task_outputs(output_dir: Path, task_id: int) -> dict:
    """Check if Claude created the expected output files."""
    expected_files = {
        "meta_file": output_dir / f"meta_{task_id}.json",
        "episode_file": output_dir / f"episode_{task_id}.py",
        "video_file": output_dir / f"episode_{task_id}.mp4",
    }
    return {
        name: path.exists()
        for name, path in expected_files.items()
    }


def get_task_success_from_meta(output_dir: Path, task_id: int) -> bool | None:
    """Parse meta file to get actual task success."""
    meta_file = output_dir / f"meta_{task_id}.json"
    if not meta_file.exists():
        return None
    try:
        with open(meta_file) as f:
            meta = json.load(f)
        return meta.get("success", None)
    except Exception:
        return None


def check_task_already_completed(output_dir: Path, task_id: int) -> bool:
    """Check if a task has already been completed (for resume mode)."""
    messages_file = output_dir / f"messages_{task_id}.json"
    if not messages_file.exists():
        return False
    try:
        with open(messages_file) as f:
            data = json.load(f)
        return data.get("agent_completed", False)
    except Exception:
        return False


def save_incremental_summary(
    output_dir: Path,
    task_id: int,
    result: dict,
    experiment: str,
    benchmark: str,
    model: str,
    total_tasks: int,
    completed_count: int,
    skipped_count: int,
) -> None:
    """Save incremental summary after each task completes."""
    summary_file = output_dir / f"run_summary_{task_id}.json"
    summary = {
        "experiment": experiment,
        "benchmark": benchmark,
        "model": model,
        "total_tasks": total_tasks,
        "completed_so_far": completed_count,
        "skipped": skipped_count,
        "last_task_id": task_id,
        "timestamp": datetime.now().isoformat(),
        "last_result": {
            "task_id": result["task_id"],
            "agent_completed": result["agent_completed"],
            "task_success": result["task_success"],
            "output_files": result.get("output_files"),
            "metadata": result.get("metadata"),
            "error": result.get("error"),
        }
    }
    with open(summary_file, "w") as f:
        json.dump(summary, f, indent=2)


async def run_claude_agent(
    prompt: str,
    task_id: int,
    output_dir: Path,
    model: str = "claude-opus-4-5-20251101",
    log_file: Path | None = None,
) -> dict:
    """
    Run Claude agent with the given prompt using the Python SDK.

    Returns:
        dict with 'agent_completed', 'task_success', 'messages', 'error' keys
    """
    output_file = output_dir / f"messages_{task_id}.json"

    def log(msg: str):
        """Write to log file if provided, otherwise stdout."""
        if log_file:
            with open(log_file, "a") as f:
                f.write(msg + "\n")
        else:
            print(msg, flush=True)

    log(f"\n{'='*60}")
    log(f"Running Claude Agent for task {task_id}")
    log(f"Output will be saved to: {output_file}")
    log(f"{'='*60}")

    result = {
        "task_id": task_id,
        "agent_completed": False,  # True if agent ran without crashing
        "task_success": None,      # Actual libero task result from meta file
        "output_files": {},        # Which expected files were created
        "messages": [],
        "session_id": None,
        "metadata": {},
        "error": None,
        "start_time": datetime.now().isoformat(),
        "end_time": None,
    }

    try:
        # Configure agent options with bypass permissions
        options = ClaudeAgentOptions(
            permission_mode="bypassPermissions",  # Bypass all permission checks
            model=model,
            cwd=AGENT_CWD,
        )

        messages = []

        # Run the agent
        async for message in query(prompt=prompt, options=options):
            messages.append(message)

            # Log progress
            if isinstance(message, AssistantMessage):
                for block in message.content:
                    if isinstance(block, ThinkingBlock):
                        # Log thinking/reasoning trace
                        thinking = block.thinking
                        if len(thinking) > 500:
                            thinking = thinking[:500] + "..."
                        log(f"  [Thinking]: {thinking}")
                    elif isinstance(block, TextBlock):
                        # Log first 200 chars of text
                        text = block.text[:200] + "..." if len(block.text) > 200 else block.text
                        log(f"  [Text]: {text}")
                    elif isinstance(block, ToolUseBlock):
                        # Log tool name and input
                        log(f"  [Tool]: {block.name}")
                        # Format tool input nicely
                        input_str = json.dumps(block.input, indent=4, default=str)
                        # Indent each line for readability
                        indented = "\n".join("    " + line for line in input_str.split("\n"))
                        log(f"  [Input]:\n{indented}")
                    elif isinstance(block, ToolResultBlock):
                        # Log tool result
                        status = "ERROR" if block.is_error else "OK"
                        content = block.content
                        if isinstance(content, str) and len(content) > 500:
                            content = content[:500] + "..."
                        elif isinstance(content, list):
                            content = json.dumps(content, default=str)[:500] + "..."
                        log(f"  [ToolResult {status}]: {content}")
            elif isinstance(message, ResultMessage):
                result["session_id"] = message.session_id
                duration_min = message.duration_ms / 60000.0 if message.duration_ms else 0
                usage = message.usage or {}
                result["metadata"] = {
                    "duration_min": round(duration_min, 2),
                    "cost_usd": message.total_cost_usd,
                    "num_turns": message.num_turns,
                    "is_error": message.is_error,
                    "usage": usage,
                }
                # Extract token counts for display
                input_tokens = usage.get("input_tokens", 0)
                output_tokens = usage.get("output_tokens", 0)
                log(f"  [Result]: Session={message.session_id}, "
                    f"Duration={duration_min:.2f}min, Cost=${message.total_cost_usd}, "
                    f"Tokens(in={input_tokens}, out={output_tokens})")

        result["end_time"] = datetime.now().isoformat()
        result["messages"] = [serialize_message(m) for m in messages]
        result["agent_completed"] = True

    except Exception as e:
        result["error"] = str(e)
        result["end_time"] = datetime.now().isoformat()
        log(f"  [Error]: {e}")

    # Validate output files and get task success from meta file
    result["output_files"] = validate_task_outputs(output_dir, task_id)
    result["task_success"] = get_task_success_from_meta(output_dir, task_id)

    # Save result to file
    output_dir.mkdir(parents=True, exist_ok=True)
    with open(output_file, "w") as f:
        json.dump(result, f, indent=2, default=str)

    # Log status
    log(f"Result saved to: {output_file}")
    log(f"Agent completed: {result['agent_completed']}")
    log(f"Task success: {result['task_success']}")
    log(f"Output files: {result['output_files']}")
    if result.get("error"):
        log(f"Error: {result['error']}")

    return result


def _assemble_episode_file(scaffold_path: str, policy_path: str, episode_path: str) -> None:
    """Stitch scaffold + policy into a single self-contained episode script.

    Replaces the dynamic importlib import in the scaffold with the actual
    policy function body so the resulting file can be re-run standalone.
    """
    with open(policy_path) as f:
        policy_source = f.read()
    with open(scaffold_path) as f:
        scaffold_source = f.read()

    assembled_lines = [
        "#!/usr/bin/env python3",
        '"""Auto-assembled episode file (scaffold + policy)."""',
        "",
    ]

    for line in scaffold_source.splitlines():
        # Skip the dynamic import block — we'll inline the policy instead
        if "importlib" in line or "spec_from_file_location" in line:
            continue
        if "module_from_spec" in line or "exec_module" in line:
            continue
        if line.strip().startswith("spec =") or line.strip().startswith("mod ="):
            continue
        # Replace mod.policy with the locally-defined policy
        line = line.replace("mod.policy", "policy")
        assembled_lines.append(line)

    # Insert the policy source right before the run_episode() call
    run_idx = next(
        (i for i, l in enumerate(assembled_lines) if "run_episode(" in l),
        len(assembled_lines),
    )
    policy_block = ["", "# --- Policy (generated by Claude) ---"] + policy_source.splitlines() + [""]
    assembled_lines[run_idx:run_idx] = policy_block

    os.makedirs(os.path.dirname(os.path.abspath(episode_path)), exist_ok=True)
    with open(episode_path, "w") as f:
        f.write("\n".join(assembled_lines) + "\n")
    print(f"[post-processing] Assembled episode file: {episode_path}")


async def run_single_task(
    task_id: int,
    task_description: str,
    template: str,
    output_dir: Path,
    model: str,
    experiment: str,
    benchmark: str,
    total_tasks: int,
    semaphore: asyncio.Semaphore,
    pbar: tqdm,
    resume: bool,
    counters: dict[str, int],
) -> Tuple[dict | None, bool]:
    """Run a single task with semaphore limiting concurrency.

    Returns:
        Tuple of (result or None if skipped, was_skipped)
    """
    async with semaphore:
        # Check if task already completed (resume mode)
        if resume and check_task_already_completed(output_dir, task_id):
            counters["skipped"] += 1
            pbar.update(1)
            return None, True

        log_file = output_dir / f"log_{task_id}.txt"

        # Pre-generate temp_dir so we can place the scaffold before prompting
        temp_dir = f"/tmp/libero_sim_{uuid.uuid4().hex[:8]}"
        os.makedirs(temp_dir, exist_ok=True)

        # Build & write the scaffold that Claude will execute (but never edit)
        meta_file = f"meta_{task_id}.json"
        video_file = f"episode_{task_id}.mp4"
        policy_file = os.path.join(temp_dir, f"policy_{task_id}.py")
        scaffold_text = generate_episode_scaffold(
            benchmark_name=benchmark,
            task_id=task_id,
            output_dir=str(output_dir.resolve()),
            harness_path=str(HARNESS_FILE),
            meta_file=meta_file,
            video_file=video_file,
            policy_file=policy_file,
        )
        scaffold_path = os.path.join(temp_dir, "scaffold.py")
        with open(scaffold_path, "w") as f:
            f.write(scaffold_text)

        prompt = format_prompt(template, task_id, task_description, output_dir, benchmark, temp_dir)

        result = await run_claude_agent(
            prompt=prompt,
            task_id=task_id,
            output_dir=output_dir,
            model=model,
            log_file=log_file,
        )

        # --- Post-processing: assemble a self-contained episode file ------
        episode_file = output_dir / f"episode_{task_id}.py"
        if not episode_file.exists() and os.path.exists(policy_file):
            _assemble_episode_file(
                scaffold_path=scaffold_path,
                policy_path=policy_file,
                episode_path=str(episode_file),
            )

        counters["completed"] += 1

        save_incremental_summary(
            output_dir=output_dir,
            task_id=task_id,
            result=result,
            experiment=experiment,
            benchmark=benchmark,
            model=model,
            total_tasks=total_tasks,
            completed_count=counters["completed"],
            skipped_count=counters["skipped"],
        )

        pbar.update(1)
        return result, False


async def run_all_tasks(
    tasks_to_run: List[Tuple[int, str]],
    template: str,
    output_dir: Path,
    model: str = "claude-opus-4-5-20251101",
    resume: bool = False,
    experiment: str = "",
    benchmark: str = "",
    parallel: int = 4,
) -> Tuple[List[dict], int]:
    """Run all tasks in parallel with progress tracking.

    Returns:
        Tuple of (results list, skipped count)
    """
    semaphore = asyncio.Semaphore(parallel)
    counters = {"completed": 0, "skipped": 0}

    # Create progress bar
    pbar = tqdm(
        total=len(tasks_to_run),
        desc="Running tasks",
        unit="task",
        dynamic_ncols=True,
        bar_format="{l_bar}{bar}| {n_fmt}/{total_fmt} [{elapsed}<{remaining}, {rate_fmt}]"
    )

    # Create all task coroutines
    coroutines = [
        run_single_task(
            task_id=task_id,
            task_description=task_description,
            template=template,
            output_dir=output_dir,
            model=model,
            experiment=experiment,
            benchmark=benchmark,
            total_tasks=len(tasks_to_run),
            semaphore=semaphore,
            pbar=pbar,
            resume=resume,
            counters=counters,
        )
        for task_id, task_description in tasks_to_run
    ]

    # Run all in parallel (limited by semaphore)
    results_with_skip = await asyncio.gather(*coroutines)

    pbar.close()

    # Separate results and count skipped
    results = [r for r, skipped in results_with_skip if not skipped]
    skipped_count = sum(1 for _, skipped in results_with_skip if skipped)

    return results, skipped_count


def main():
    parser = argparse.ArgumentParser(
        description="Execute Claude Agent SDK on LIBERO benchmark tasks",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
    # List benchmarks
    python run_libero_claude.py --list-benchmarks

    # List tasks in a benchmark
    python run_libero_claude.py --list-tasks --benchmark libero_10

    # Run a specific task
    python run_libero_claude.py --experiment my_exp --task-id 0

    # Run all tasks
    python run_libero_claude.py --experiment my_exp --all --benchmark libero_spatial
        """
    )

    parser.add_argument(
        "--task-id",
        type=int,
        help="Specific task ID to run"
    )
    parser.add_argument(
        "--all",
        action="store_true",
        help="Run all tasks in the benchmark (required to run multiple tasks)"
    )
    parser.add_argument(
        "--benchmark",
        type=str,
        default="libero_spatial",
        help="LIBERO benchmark to use (default: libero_spatial)"
    )
    parser.add_argument(
        "--list-tasks",
        action="store_true",
        help="List all tasks in the benchmark and exit"
    )
    parser.add_argument(
        "--list-benchmarks",
        action="store_true",
        help="List available benchmarks and exit"
    )
    parser.add_argument(
        "--experiment",
        type=str,
        help="Experiment name (required for running tasks, creates data/{experiment}/ folder)"
    )
    parser.add_argument(
        "--model",
        type=str,
        default="claude-opus-4-5-20251101",
        help="Model to use (default: claude-opus-4-5-20251101)"
    )
    parser.add_argument(
        "--resume",
        action="store_true",
        help="Resume experiment, skipping tasks with existing successful results"
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Force overwrite existing experiment folder"
    )
    parser.add_argument(
        "--parallel",
        type=int,
        default=4,
        help="Number of parallel workers (default: 4)"
    )
    parser.add_argument(
        "--prompt-template",
        type=str,
        default=None,
        help="Path to custom prompt template file (default: src/prompt_template.md)"
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default=None,
        help="Custom output base directory (default: data/)"
    )

    args = parser.parse_args()

    # Handle --list-benchmarks
    if args.list_benchmarks:
        benchmarks = list_benchmarks()
        print("\nAvailable benchmarks:")
        for name, info in benchmarks.items():
            print(f"  {name}: {info['description']} ({info['tasks']} tasks)")
        return 0

    # Get tasks from libero (needed for --list-tasks)
    if args.list_tasks or args.task_id is not None or args.all:
        print(f"Loading tasks from benchmark: {args.benchmark}")
        tasks = get_libero_tasks(args.benchmark)

    # Handle --list-tasks
    if args.list_tasks:
        print(f"\nAvailable tasks in {args.benchmark}:")
        for task_id, task_name in tasks:
            print(f"  {task_id}: {task_name}")
        return 0

    # Validate arguments for running experiments
    if args.task_id is None and not args.all:
        parser.error("Must specify --task-id, --all, --list-tasks, or --list-benchmarks")

    if not args.experiment:
        parser.error("--experiment is required when running tasks")

    # Check for existing experiment folder
    if args.output_dir:
        output_dir = Path(args.output_dir) / args.experiment
    else:
        output_dir = DATA_DIR / args.experiment
    if output_dir.exists() and any(output_dir.iterdir()):
        if not args.resume and not args.force:
            print(f"Error: Experiment folder '{output_dir}' already exists with files.")
            print("Use --resume to continue from where you left off, or --force to overwrite.")
            return 1
        if args.force and not args.resume:
            print(f"Warning: --force specified, will overwrite existing results.")

    # Create experiment output directory
    output_dir.mkdir(parents=True, exist_ok=True)
    print(f"Experiment: {args.experiment}")
    print(f"Output directory: {output_dir}")
    if args.resume:
        print("Resume mode: will skip tasks with existing successful results")

    # Load and save prompt template to experiment folder
    template_source = args.prompt_template if args.prompt_template else str(PROMPT_TEMPLATE_PATH)
    print(f"Loading prompt template from: {template_source}")
    template = load_prompt_template(args.prompt_template)
    template_copy_path = output_dir / "prompt_template.md"
    with open(template_copy_path, "w") as f:
        f.write(template)
    print(f"Prompt template saved to: {template_copy_path}")

    # Determine which tasks to run
    if args.task_id is not None:
        # Validate task_id
        valid_ids = [t[0] for t in tasks]
        if args.task_id not in valid_ids:
            print(f"Error: task_id {args.task_id} not found. Valid IDs: {valid_ids}")
            return 1
        tasks_to_run = [(args.task_id, dict(tasks)[args.task_id])]
    else:
        # Run all tasks
        tasks_to_run = tasks

    print(f"Tasks to run: {len(tasks_to_run)}")
    print(f"Parallel workers: {args.parallel}")

    # Run tasks using asyncio
    results, skipped_count = asyncio.run(run_all_tasks(
        tasks_to_run=tasks_to_run,
        template=template,
        output_dir=output_dir,
        model=args.model,
        resume=args.resume,
        experiment=args.experiment,
        benchmark=args.benchmark,
        parallel=args.parallel,
    ))

    # Summary
    print(f"\n{'='*60}")
    print("SUMMARY")
    print(f"{'='*60}")
    agent_completed = sum(1 for r in results if r["agent_completed"])
    task_succeeded = sum(1 for r in results if r["task_success"] is True)
    print(f"Agent completed: {agent_completed}/{len(results)}")
    print(f"Task succeeded: {task_succeeded}/{len(results)}")
    if skipped_count > 0:
        print(f"Skipped (resume): {skipped_count}")

    for r in results:
        agent_status = "OK" if r["agent_completed"] else "FAIL"
        task_status = "PASS" if r["task_success"] is True else ("FAIL" if r["task_success"] is False else "N/A")
        error_msg = f" - {r.get('error', '')}" if r.get("error") else ""
        print(f"  [Agent:{agent_status}][Task:{task_status}] Task {r['task_id']}{error_msg}")

    # Calculate aggregate token usage
    total_input_tokens = 0
    total_output_tokens = 0
    total_cost_usd = 0.0
    for r in results:
        metadata = r.get("metadata", {})
        usage = metadata.get("usage", {})
        total_input_tokens += usage.get("input_tokens", 0)
        total_output_tokens += usage.get("output_tokens", 0)
        total_cost_usd += metadata.get("cost_usd", 0) or 0

    # Save summary
    summary_file = output_dir / "run_summary.json"
    summary = {
        "experiment": args.experiment,
        "benchmark": args.benchmark,
        "model": args.model,
        "total_tasks": len(tasks_to_run),
        "agent_completed": agent_completed,
        "task_succeeded": task_succeeded,
        "skipped": skipped_count,
        "timestamp": datetime.now().isoformat(),
        "total_usage": {
            "input_tokens": total_input_tokens,
            "output_tokens": total_output_tokens,
            "total_tokens": total_input_tokens + total_output_tokens,
            "cost_usd": round(total_cost_usd, 4),
        },
        "results": [
            {
                "task_id": r["task_id"],
                "agent_completed": r["agent_completed"],
                "task_success": r["task_success"],
                "output_files": r.get("output_files"),
                "session_id": r.get("session_id"),
                "metadata": r.get("metadata"),
                "error": r.get("error")
            }
            for r in results
        ]
    }
    with open(summary_file, "w") as f:
        json.dump(summary, f, indent=2)
    print(f"\nSummary saved to: {summary_file}")

    # Exit with 0 if all agents completed, 1 otherwise
    return 0 if agent_completed == len(results) else 1


if __name__ == "__main__":
    sys.exit(main())
